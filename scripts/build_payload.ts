/**
 * Writes the compressed datasets to lib/ as shared CommonJS modules.
 *
 * The Node (CJS) and ESM bundles both reference these files at runtime instead of
 * embedding a copy of the payload, which removes four duplicated ~1 MB strings from
 * the published package. The browser bundles still embed the payload so `dist/`
 * stays self-contained.
 *
 * Usage: npx tsx scripts/build_payload.ts
 */

import fs from 'node:fs';
import path from 'node:path';

const SOURCES = [
    ['airports.data.json', 'payload.full.js'],
    ['airports.lite.data.json', 'payload.lite.js'],
] as const;

const SRC_DIR = path.join(__dirname, '../src');
const OUT_DIR = path.join(__dirname, '../lib');

fs.mkdirSync(OUT_DIR, { recursive: true });

for (const [source, output] of SOURCES) {
    const payload = fs.readFileSync(path.join(SRC_DIR, source), 'utf8').trim();
    const contents = `// Generated by scripts/build_payload.ts. Do not edit.\nmodule.exports = ${payload};\n`;
    fs.writeFileSync(path.join(OUT_DIR, output), contents);
    console.log(`Wrote lib/${output} (${(contents.length / 1024 / 1024).toFixed(2)} MB)`);
}
